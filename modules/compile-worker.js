
/**
compileWorker(code, options)

Creates a Web Worker from a string of JS `code` (already instrumented with
`self.onmessage` expecting `{ id, data }` and replying with `{ id, data }` or
`{ id, error }`, as generated by `deno/make-worker.js`) and wraps it as an
async function `(data, transfers) => Promise`.
**/

const defaults = { type: 'module' };

export default function compileWorker(code, options = defaults) {
    const blob   = new Blob([code], { type: 'application/javascript' });
    const url    = URL.createObjectURL(blob);
    const worker = new Worker(url, options);
    const jobs   = new Map();
    let id = 0;
    let revoked = false;
    let terminated = false;

    function revoke() {
        if (revoked) return;
        revoked = true;
        URL.revokeObjectURL(url);
    }

    function cancel(error) {
        revoke();
        for (const job of jobs.values()) job.reject(error);
        jobs.clear();
    }

    worker.onmessage = ({ data: message }) => {
        revoke();
        const job = jobs.get(message.id);
        if (!job) return;
        jobs.delete(message.id);
        if ('error' in message) job.reject(message.error);
        else job.resolve(message.data);
    };

    worker.onerror = (e) => {
        cancel(e.error || new Error(e.message || 'Worker error'));
    };

    function run(data, transfers) {
        if (terminated) return Promise.reject(new Error('Worker terminated'));
        return new Promise((resolve, reject) => {
            const jobId = ++id;
            worker.postMessage({ id: jobId, data }, transfers);
            jobs.set(jobId, { resolve, reject });
        });
    }

    run.terminate = () => {
        if (terminated) return;
        terminated = true;
        cancel(new Error('Worker terminated'));
        worker.terminate();
    };

    return run;
}
